@app.route("/stock")
def stock():
    if not session.get("user"):
        return redirect("/")

    conn = sqlite3.connect("database.db")
    cursor = conn.cursor()

    q = request.args.get("q")
    if q:
        cursor.execute("SELECT * FROM medicines WHERE name LIKE ?", ('%' + q + '%',))
    else:
        cursor.execute("SELECT * FROM medicines")

    data = cursor.fetchall()

    today = datetime.today().date()
    expired = 0
    exp7 = 0
    exp30 = 0
    low = 0

    for m in data:
        try:
            if int(m[2]) < 5:
                low += 1
        except:
            pass

        try:
            exp_date = datetime.strptime(m[3], "%Y-%m-%d").date()
            days = (exp_date - today).days
            if days < 0:
                expired += 1
            elif days <= 7:
                exp7 += 1
            elif days <= 30:
                exp30 += 1
        except:
            pass

    conn.close()
    return render_template("stock.html", medicines=data, expired=expired, exp7=exp7, exp30=exp30, low=low)


