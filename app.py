def send_email(low_items):
    try:
        sender = "your_email@gmail.com"
        password = "your_app_password"
        receiver = "supplier@gmail.com"

        server = smtplib.SMTP("smtp.gmail.com", 587)
        server.starttls()
        server.login(sender, password)

        # 🧠 BUILD SMART CONTENT
        message = "Subject: 🚨 Medicine Reorder Request - Low Stock Alert\n\n"

        message += "Hello Supplier,\n\n"
        message += "We have identified the following medicines running low in stock:\n\n"

        message += "-------------------------------------\n"

        for i, item in enumerate(low_items, start=1):
            message += f"{i}. {item}\n"

        message += "-------------------------------------\n\n"

        message += "Kindly arrange to supply the above items at the earliest.\n\n"

        message += "This is an automated alert generated by the Pharmacy System.\n\n"

        message += "Thank you,\n"
        message += "Pharmacy Management System 💊"

        server.sendmail(sender, receiver, message)
        server.quit()

        print("📧 Email sent successfully")

    except Exception as e:
        print("Email error:", e)


