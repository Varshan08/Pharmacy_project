@app.route("/add", methods=["POST"])
def add():

    try:
        barcode = request.form.get("barcode")
        name = request.form.get("name")
        quantity = int(request.form.get("quantity", 0))
        expiry = request.form.get("expiry")
        price = request.form.get("price")

        conn = sqlite3.connect("database.db")
        cursor = conn.cursor()

        if barcode:

            cursor.execute(
                "SELECT * FROM medicines WHERE barcode=?",
                (barcode,)
            )

            existing = cursor.fetchone()

            if existing:
                old_qty = int(existing[2])
                new_qty = old_qty + quantity

                cursor.execute(
                    "UPDATE medicines SET quantity=? WHERE barcode=?",
                    (new_qty, barcode)
                )

            else:
                cursor.execute(
                    "INSERT INTO medicines (name,quantity,expiry,price,barcode) VALUES (?,?,?,?,?)",
                    (name, quantity, expiry, price, barcode)
                )

        else:

            cursor.execute(
                "SELECT * FROM medicines WHERE name=?",
                (name,)
            )

            existing = cursor.fetchone()

            if existing:
                old_qty = int(existing[2])
                new_qty = old_qty + quantity

                cursor.execute(
                    "UPDATE medicines SET quantity=? WHERE name=?",
                    (new_qty, name)
                )

            else:
                cursor.execute(
                    "INSERT INTO medicines (name,quantity,expiry,price) VALUES (?,?,?,?)",
                    (name, quantity, expiry, price)
                )

        conn.commit()
        conn.close()

        return redirect("/stock")

    except Exception as e:
        return f"Error: {e}"


