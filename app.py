@app.route("/check_alerts")
def check_alerts():

    global last_email_sent

    conn = sqlite3.connect("database.db")
    cursor = conn.cursor()

    cursor.execute("SELECT * FROM medicines")
    data = cursor.fetchall()

    conn.close()

    low = []
    exp = []

    today = datetime.today().date()

    for m in data:

        try:
            if int(m[2]) < 5:
                low.append(m[1])
        except:
            pass

        try:
            exp_date = datetime.strptime(m[3], "%Y-%m-%d").date()
            if (exp_date - today).days <= 7:
                exp.append(m[1])
        except:
            pass

    email_status = None

    if low and low != last_email_sent:
        try:
            send_email("Low stock items: " + ", ".join(low))
            email_status = "success"
            last_email_sent = low.copy()
        except:
            email_status = "error"

    return {
        "low": low,
        "exp": exp,
        "email_status": email_status
    }


