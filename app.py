@app.route("/dashboard")
def dashboard():

    conn = sqlite3.connect("database.db")
    cursor = conn.cursor()

    cursor.execute("SELECT * FROM medicines")
    data = cursor.fetchall()

    low = 0
    exp = 0
    expired = 0

    low_list = []
    exp_list = []

    today = datetime.today().date()

    for m in data:

        try:
            qty = int(m[2])
        except:
            qty = 0

        if qty < 5:
            low += 1
            low_list.append(m[1])

        try:
            exp_date = datetime.strptime(m[3], "%Y-%m-%d").date()

            if exp_date < today:
                expired += 1

            elif (exp_date - today).days <= 7:
                exp += 1
                exp_list.append(m[1])

        except:
            pass

    conn.close()

    return render_template(
        "dashboard.html",
        low=low,
        exp=exp,
        expired=expired,
        low_list=low_list,
        exp_list=exp_list
    )


